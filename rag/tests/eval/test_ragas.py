"""
RAGAS evaluation of the running RAG service. Opt-in, because it needs Qdrant,
Ollama, the RAG service and an LLM key. Easiest way to run it: ``scripts/eval.sh``. Manually:

    RUN_RAGAS=1 EVAL_LLM_API_KEY=... uv run pytest tests/eval/test_ragas.py -s

Writes tests/eval/RESULTS.md and fails if context_precision < 0.75, faithfulness < 0.80
or noise_sensitivity > 0.20.
"""

from __future__ import annotations

import json
import os
import statistics
import time
from datetime import datetime, timezone
from pathlib import Path

import httpx
import pytest

from ragas_metrics import (
    LLM_MODEL,
    NOISE_CHUNKS,
    answer,
    claim_share,
    context_precision,
    context_recall,
    doc_of,
    judge_claims,
)

RAG_URL = os.getenv("RAG_URL", "http://localhost:8002")
API_KEY = os.getenv("EVAL_LLM_API_KEY", "")
EVAL_SET = Path(__file__).resolve().parents[2] / "data" / "ragas_eval.jsonl"
DOCS = Path(__file__).resolve().parents[2] / "data" / "docs"
RESULTS = Path(__file__).resolve().parent / "RESULTS.md"
DELAY = float(os.getenv("EVAL_DELAY_SECONDS", "15"))  # free-tier tokens-per-minute limit

pytestmark = pytest.mark.skipif(
    os.getenv("RUN_RAGAS") != "1" or not API_KEY, reason="set RUN_RAGAS=1 and EVAL_LLM_API_KEY to run"
)


def mean(values: list[float | None]) -> float:
    present = [v for v in values if v is not None]
    return round(statistics.mean(present), 3) if present else 0.0


def retrieve(client: httpx.Client, i: int, question: str) -> dict:
    """POST /knowledge, retrying once if the service is momentarily stalled."""
    for attempt in range(2):
        try:
            return client.post(f"{RAG_URL}/knowledge", timeout=180, json={
                "query_id": f"ragas-{i}", "semantic_query": question, "source_filters": [],
                "time_window": {"not_after": datetime.now(timezone.utc).isoformat()},
                "max_chunks": 5, "compression_budget_tokens": 2000,
            }).json()
        except httpx.TimeoutException:
            if attempt:
                raise
    raise AssertionError("unreachable")


def test_ragas_thresholds() -> None:
    items = [json.loads(line) for line in EVAL_SET.read_text().splitlines() if line.strip()]
    rows = []
    with httpx.Client(timeout=300) as client:
        client.post(f"{RAG_URL}/ingest", json={"source_type": "local_file", "full_reindex": True}).raise_for_status()
        for i, item in enumerate(items):
            if i:
                time.sleep(DELAY)
            result = retrieve(client, i, item["question"])
            chunks = result["chunks"]
            docs = [doc_of(c["chunk_id"]) for c in chunks]
            contexts = [c["content"] for c in chunks]
            relevant = set(item["relevant_docs"])

            clean = answer(API_KEY, item["question"], contexts)
            noisy = answer(API_KEY, item["question"], contexts + NOISE_CHUNKS)
            faithful = claim_share(judge_claims(API_KEY, clean, contexts, "supported"), "supported")
            correct = claim_share(judge_claims(API_KEY, noisy, [item["ground_truth"]], "correct"), "correct")
            rows.append({
                "question": item["question"], "retrieved": docs,
                "precision": context_precision(docs, relevant), "recall": context_recall(docs, relevant),
                "faithfulness": faithful, "noise": None if correct is None else 1 - correct,
            })
            print(f"  {i + 1:2d} P={rows[-1]['precision']:.2f} R={rows[-1]['recall']:.2f} "
                  f"F={faithful} noise={rows[-1]['noise']}  {item['question'][:60]}")

    scores = {
        "context_precision": mean([r["precision"] for r in rows]),
        "context_recall": mean([r["recall"] for r in rows]),
        "faithfulness": mean([r["faithfulness"] for r in rows]),
        "noise_sensitivity": mean([r["noise"] for r in rows]),
    }
    write_results(scores, rows)
    assert scores["context_precision"] >= 0.75, scores
    assert scores["faithfulness"] >= 0.80, scores
    assert scores["noise_sensitivity"] <= 0.20, scores


def write_results(scores: dict[str, float], rows: list[dict]) -> None:
    targets = {"context_precision": ">= 0.75", "context_recall": "(no target)",
               "faithfulness": ">= 0.80", "noise_sensitivity": "<= 0.20"}
    lines = [
        "# RAG evaluation (RAGAS-style)",
        "",
        f"Generated by `tests/eval/test_ragas.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC "
        f"with judge/answer model `{LLM_MODEL}`. Do not edit by hand.",
        "",
        f"{len(rows)} questions from `data/ragas_eval.jsonl` against the {len(list(DOCS.glob('*.md')))} documents "
        "in `data/docs` (top 5 chunks per question). Precision/recall use labelled relevant",
        "documents; faithfulness and noise sensitivity use an LLM answer plus an LLM judge.",
        "`scripts/eval.sh` gives RAG no chat LLM, so when the NLI step flags a conflict the multi-agent",
        "debate cannot run and RAG's fallback (keep the higher-ranked document) is what gets measured.",
        "",
        "| Metric | Score | Target |",
        "|---|---|---|",
        *[f"| {name} | {value} | {targets[name]} |" for name, value in scores.items()],
        "",
        "| Question | Retrieved (in order) | Precision | Recall | Faithfulness | Noise |",
        "|---|---|---|---|---|---|",
        *[f"| {r['question']} | {', '.join(r['retrieved'])} | {r['precision']:.2f} | {r['recall']:.2f} | "
          f"{r['faithfulness']} | {r['noise']} |" for r in rows],
    ]
    RESULTS.write_text("\n".join(lines) + "\n")
